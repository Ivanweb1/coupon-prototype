let uid = 0;
function makeCode() {
  const words = ["SALE", "GOOD", "CITY", "MORE", "GIFT", "OPEN"];
  return words[Math.floor(Math.random() * words.length)] +
         String(Math.floor(100 + Math.random() * 899));
}

/* Одна и та же акция может быть у разных компаний — так лента
   не выглядит повтором, когда офферов-заготовок мало. */
const BRANDS = ["Рыба", "Название", "Пример", "Компания", "Бренд"];
function swapBrand(company) {
  const b = BRANDS[Math.floor(Math.random() * BRANDS.length)];
  return company.replace(/«[^»]+»/, "«" + b + "»");
}

window.makeCoupon = function (catId) {
  const cat = CATEGORIES.find(c => c.id === catId) ||
              CATEGORIES[Math.floor(Math.random() * CATEGORIES.length)];
  const pool = SEEDS[cat.id] || SEEDS.services;
  const seed = pool[Math.floor(Math.random() * pool.length)];
  const terms = [];
  const shuffled = TERMS.slice().sort(() => Math.random() - .5);
  for (let i = 0; i < 3; i++) terms.push(shuffled[i]);
  return {
    id: ++uid,
    cat: cat,
    title: seed[0],
    value: seed[1],
    company: swapBrand(seed[2]),
    code: makeCode(),
    address: STREETS[Math.floor(Math.random() * STREETS.length)],
    views: Math.floor(120 + Math.random() * 4200),
    dist: Math.floor(120 + Math.random() * 7800),   /* метров до точки */
    left: Math.floor(3 + Math.random() * 40),
    until: ["до 30 сентября", "до конца месяца", "ещё 12 дней", "до 15 октября"][Math.floor(Math.random() * 4)],
    terms: terms
  };
};

/* Стараемся не повторять один и тот же оффер внутри выдачи —
   иначе на демо лента выглядит как ошибка. */
window.makeBatch = function (n, catId) {
  const out = [];
  const used = new Set();
  for (let i = 0; i < n; i++) {
    let c = makeCoupon(catId);
    for (let t = 0; t < 12 && used.has(c.title + c.company); t++) c = makeCoupon(catId);
    used.add(c.title + c.company);
    out.push(c);
  }
  return out;
};
